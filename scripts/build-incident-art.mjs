// Writes the incident picture stories for the site from scripts/incident-scenes.js:
//   public/incidents/<record id>-<a|b|c>.svg   one drawing per panel (speech bubbles drawn, words left out)
//   src/data/incidentStories.ts                captions and the words that sit on top of each drawing
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const src = readFileSync(new URL('scripts/incident-scenes.js', root), 'utf8');
const { INCIDENTS } = new Function(`${src}\nreturn { INCIDENTS };`)();

mkdirSync(new URL('public/incidents/', root), { recursive: true });
const stories = {};
for (const inc of INCIDENTS) {
  stories[inc.id] = {
    title: inc.title,
    panels: inc.panels.map((p, i) => {
      const file = `incidents/${inc.id}-${'abc'[i]}.svg`;
      writeFileSync(new URL(`public/${file}`, root), p.svg);
      return {
        file,
        caption: p.caption,
        says: p.says.map(({ text, x, y, w, red }) => ({ text, x, y, w, red })),
        words: p.words,
      };
    }),
  };
}

const ts = `// Generated by scripts/build-incident-art.mjs from scripts/incident-scenes.js — run \`npm run art\` after editing the scenes.
export interface StoryText {
  text: string;
  x: number;
  y: number;
  red: boolean;
}
export interface StoryPanel {
  file: string;
  caption: string;
  says: (StoryText & { w: number })[];
  words: (StoryText & { size: number; rot: number })[];
}
export interface IncidentStory {
  title: string;
  panels: StoryPanel[];
}

export const INCIDENT_STORIES: Record<string, IncidentStory> = ${JSON.stringify(stories, null, 2)};
`;
writeFileSync(new URL('src/data/incidentStories.ts', root), ts);
console.log(`Wrote ${INCIDENTS.length} stories (${INCIDENTS.length * 3} drawings).`);
